// Optional QA runner: supply a local Playwright module and an authorized image path.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import { validateLevel, replaySolution, bounds, position } from '../src/core.js';
const { chromium } = await import(process.env.HEX_MAP_PLAYWRIGHT ? pathToFileURL(process.env.HEX_MAP_PLAYWRIGHT).href : 'playwright');
const root = fileURLToPath(new URL('../', import.meta.url));
const output = path.join(root, '.artifacts'); await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.HEX_MAP_CHROMIUM || chromium.executablePath() });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [], checks = []; page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
try {
  await page.goto(process.env.HEX_MAP_URL || 'http://localhost:4173');
  await page.getByRole('heading', { name: 'Hex Map Studio', exact: true }).waitFor();
  assert.ok(await page.locator('#download').isDisabled()); checks.push('unverified export disabled');
  await page.locator('#validate').click(); await page.locator('.check-box[data-state=success]').waitFor();
  assert.ok(await page.locator('#download').isEnabled()); checks.push('demo validates and enables export');
  await page.getByRole('button', { name: 'Ban đầu', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Ban đầu', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.locator('#seed').fill('43'); assert.ok(await page.locator('#download').isDisabled()); checks.push('parameter edit invalidates export');
  await page.locator('#mode').selectOption('timed'); await page.locator('#timer').fill('0');
  await page.locator('#validate').click(); await page.locator('.check-box[data-state=error]').waitFor();
  assert.ok(await page.locator('#download').isDisabled()); checks.push('invalid timer blocked');
  await page.locator('#mode').selectOption('relaxed');
  if (!process.env.HEX_MAP_TEST_IMAGE) throw new Error('HEX_MAP_TEST_IMAGE is required for image import QA');
  await page.locator('#image-file').setInputFiles(process.env.HEX_MAP_TEST_IMAGE);
  await page.locator('#file-name').filter({ hasText: /×/ }).waitFor();
  await page.locator('#sample').click(); await page.locator('#board-subtitle').filter({ hasText: 'Đã chuyển ảnh' }).waitFor();
  checks.push('real local image decoded and sampled into hex targets');
  await page.locator('#level-id').fill('browser-image-01'); await page.locator('#validate').click();
  await page.locator('.check-box[data-state=success]').waitFor();
  const fixtures = path.join(output, 'fixtures'); await mkdir(fixtures, { recursive: true });
  const [mapDownload] = await Promise.all([page.waitForEvent('download'), page.locator('#download').click()]);
  const mapPath = path.join(fixtures, 'browser-image-01.json'); await mapDownload.saveAs(mapPath);
  const [solutionDownload] = await Promise.all([page.waitForEvent('download'), page.locator('#report').click()]);
  const solutionPath = path.join(fixtures, 'browser-image-01.solution.json'); await solutionDownload.saveAs(solutionPath);
  const level = JSON.parse(await readFile(mapPath, 'utf8')), witness = JSON.parse(await readFile(solutionPath, 'utf8'));
  validateLevel(level); assert.ok(replaySolution(level, witness)); checks.push('actual browser-downloaded JSON and witness replay');
  assert.equal(Object.keys(level).length, 13); assert.ok(level.cells.length > 500); checks.push('dense map export has no image field');
  await page.getByRole('button', { name: 'Màu đích', exact: true }).click();
  await page.screenshot({ path: path.join(output, 'workbench-desktop.png'), fullPage: true });
  const box = bounds(level.cells), rect = await page.locator('#board').boundingBox();
  const scale = Math.min((rect.width - 50) / box.width, (rect.height - 60) / box.height);
  const center = position(level.cells[Math.floor(level.cells.length / 2)]);
  const click = { x: (center.x - box.left - box.width / 2) * scale + rect.width / 2,
    y: (center.y - box.top - box.height / 2) * scale + rect.height / 2 };
  await page.locator('#edit-mode').selectOption('erase'); await page.locator('#board').click({ position: click });
  assert.ok(await page.locator('#download').isDisabled());
  assert.match(await page.locator('#map-summary').innerText(), new RegExp((level.cells.length - 1).toLocaleString('vi-VN')));
  await page.locator('#undo').click(); assert.match(await page.locator('#map-summary').innerText(), new RegExp(level.cells.length.toLocaleString('vi-VN')));
  checks.push('canvas erase and undo update target data and invalidate export');
  const paintedIndex = Math.floor(level.cells.length / 2), paintColor = level.cells[paintedIndex].targetColorId === 1 ? 2 : 1;
  await page.locator('#edit-mode').selectOption('paint'); await page.locator('#paint-color').selectOption(String(paintColor));
  await page.locator('#board').click({ position: click }); await page.locator('#validate').click();
  await page.locator('.check-box[data-state=success]').waitFor();
  const painted = JSON.parse(await page.locator('#json-preview').textContent());
  assert.equal(painted.cells[paintedIndex].targetColorId, paintColor);
  assert.equal(painted.cells.filter((c, i) => c.targetColorId !== level.cells[i].targetColorId).length, 1);
  await page.locator('#undo').click(); checks.push('paint edits one target cell, rebalances initial colors and revalidates');
  await page.locator('#columns').fill('20'); assert.ok(await page.locator('#download').isDisabled());
  await page.locator('#validate').click(); await page.locator('.check-box[data-state=error]').waitFor();
  assert.match(await page.locator('#status').innerText(), /Chuyển ảnh thành ô/); checks.push('stale sampling settings cannot export');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: path.join(output, 'workbench-mobile.png'), fullPage: true }); checks.push('390px viewport has no horizontal overflow');
  assert.deepEqual(errors, []); checks.push('no browser console or page errors');
  await writeFile(path.join(output, 'browser-verification.json'), JSON.stringify({ result: 'HEX_MAP_STUDIO_BROWSER_OK', checks,
    cells: level.cells.length, witnessCommands: witness.actions.length, browser: 'headless Chromium', unityExecuted: false, deviceExecuted: false }, null, 2) + '\n');
  console.log(`HEX_MAP_STUDIO_BROWSER_OK checks=${checks.length} cells=${level.cells.length}`);
} finally { await browser.close(); }
